"""Build the airline and aircraft seed migration from OpenFlights data.

Usage: python -I scripts/build-airline-aircraft-seed.py airlines.dat planes.dat out.sql

airlines.dat: https://raw.githubusercontent.com/jpatokal/openflights/master/data/airlines.dat
planes.dat:   https://raw.githubusercontent.com/jpatokal/openflights/master/data/planes.dat
OpenFlights data is under the Open Database License (ODbL); see https://openflights.org/data.

Airline names are out of date in places (FA is "Epic Holiday", not FlySafair), so every
airline goes in unconfirmed: the edit screen asks a Consultant to confirm or correct a
name once, and the PDF shows only the code until then. Codes that two "active" airlines
share get no suggestion at all. Aircraft names are reliable and go in as they are, plus a
few common variants the list lacks.
"""
import collections, csv, sys

airlines_dat, planes_dat, out = sys.argv[1:4]
NULL = chr(92) + "N"  # OpenFlights writes missing values as backslash-N

def q(s):
    return "'" + s.replace("'", "''") + "'"

active = [r for r in csv.reader(open(airlines_dat, encoding="utf-8"))
          if r[7] == "Y" and len(r[3]) == 2 and r[3] not in ("", NULL, "-")]
count = collections.Counter(r[3].upper() for r in active)
airlines = sorted({r[3].upper(): r[1].strip() for r in active if count[r[3].upper()] == 1}.items())

aircraft = {r[1].upper(): r[0].strip() for r in csv.reader(open(planes_dat, encoding="utf-8"))
            if len(r[1]) == 3 and r[1] != NULL}
for code, name in {
    "73H": "Boeing 737-800 (winglets)", "73W": "Boeing 737-700 (winglets)", "7M9": "Boeing 737 MAX 9",
    "32A": "Airbus A320 (sharklets)", "32B": "Airbus A321 (sharklets)", "31N": "Airbus A319neo",
    "32Q": "Airbus A321neo", "339": "Airbus A330-900", "351": "Airbus A350-1000", "78J": "Boeing 787-10",
    "221": "Airbus A220-100", "223": "Airbus A220-300", "E75": "Embraer 175", "295": "Embraer E195-E2",
}.items():
    aircraft.setdefault(code, name)

with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("-- TTD quoting app: migration 0013. GENERATED by scripts/build-airline-aircraft-seed.py; do not edit.\n")
    f.write("-- Run in the Supabase SQL editor after 0012. Safe to re-run: confirmed airlines are never touched.\n")
    f.write("-- Data: OpenFlights (https://openflights.org/data), Open Database License (ODbL).\n\n")
    f.write("insert into public.airlines (iata, name) values\n")
    f.write(",\n".join(f"  ({q(c)}, {q(n)})" for c, n in airlines))
    f.write("\non conflict (iata) do update set name = excluded.name where not public.airlines.confirmed;\n\n")
    f.write("insert into public.aircraft (iata, name) values\n")
    f.write(",\n".join(f"  ({q(c)}, {q(n)})" for c, n in sorted(aircraft.items())))
    f.write("\non conflict (iata) do update set name = excluded.name;\n")

print(f"{len(airlines)} airlines ({sum(1 for v in count.values() if v > 1)} shared codes skipped), {len(aircraft)} aircraft -> {out}")
